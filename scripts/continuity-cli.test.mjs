import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const cli = fileURLToPath(new URL('./unit.mjs', import.meta.url));
test('public goal registration checks its source and binds an eligible unit', async t => {
  const root = await mkdtemp(path.join(tmpdir(),'goal-cli-')); t.after(() => rm(root,{recursive:true,force:true}));
  const file = path.join(root,'goal.md'); const bytes = 'Goal: deliver both units\n'; await writeFile(file,bytes);
  const source = {path:file,digest:`sha256:${createHash('sha256').update(bytes).digest('hex')}`};
  const goal = {id:'g1',objective:'deliver',criteria:['verified'],remaining:['u1'],status:'active'};
  const policy = {runtime:'cmux',provider:'codex',account:'/account',model:'model',effort:'high',argv:['codex']};
  await mkdir(path.join(root,'state'), {recursive:true});
  await writeFile(path.join(root,'state','policy.json'),JSON.stringify({goal:{class:'task'},session:policy}));
  const request = path.join(root,'goal.json'); await writeFile(request,JSON.stringify({goal,source}));
  const run = (...args) => spawnSync(process.execPath,[cli,...args,'--state-root',path.join(root,'state'),'--project-root',root],{cwd:root,encoding:'utf8'});
  assert.equal(run('goal','create','g1','--request',request).status,0);
  const unit = path.join(root,'unit.json'); await writeFile(unit,JSON.stringify({kind:'impl',goalId:'g1',request:{text:'work',userInputRef:'user'}}));
  assert.equal(run('unit','start','u1','--request',unit,'--non-interactive').status,0);
  assert.notEqual(run('unit','start','u2','--request',unit,'--non-interactive').status,0);
  await writeFile(file,'changed');
  assert.notEqual(run('goal','create','g1','--request',request).status,0);
});

test('an approved work-policy change reaches an active goal only through a verified policy refresh', async t => {
  const root = await mkdtemp(path.join(tmpdir(),'goal-refresh-')); t.after(() => rm(root,{recursive:true,force:true}));
  const file = path.join(root,'goal.md'); const bytes = 'Goal: deliver\n'; await writeFile(file,bytes);
  const source = {path:file,digest:`sha256:${createHash('sha256').update(bytes).digest('hex')}`};
  const policy = {runtime:'cmux',provider:'claude',account:'/account',model:'model',effort:'high',argv:['claude']};
  const state = path.join(root,'state'); await mkdir(state,{recursive:true});
  const savePolicy = session => writeFile(path.join(state,'policy.json'),JSON.stringify({goal:{class:'task'},session}));
  await savePolicy(policy);
  const request = path.join(root,'goal.json'); await writeFile(request,JSON.stringify({goal:{id:'g1',objective:'deliver',criteria:['verified'],remaining:['u1','u2'],status:'active'},source}));
  const adapters = path.join(root,'adapters.mjs');
  await writeFile(adapters,`export function createRuntimeAdapters(){ return { provider: { verifyUserInput: input => ({ ...input, verified: input.userInputRef === 'user-1' && input.effect === 'goal.policy.refresh' }) } }; }`);
  const run = (...args) => spawnSync(process.execPath,[cli,...args,'--state-root',state,'--project-root',root],{cwd:root,encoding:'utf8'});
  const result = child => JSON.parse(child.stdout.slice(child.stdout.lastIndexOf('RESULT ')+7));
  assert.equal(run('goal','create','g1','--request',request).status,0);
  await savePolicy({...policy,roles:{review:{model:'review-model'}}});
  const unit = path.join(root,'unit.json'); await writeFile(unit,JSON.stringify({kind:'impl',goalId:'g1',request:{text:'work',userInputRef:'user'}}));
  assert.equal(result(run('unit','start','u2','--request',unit,'--non-interactive')).error,'CONTINUITY_STALE');
  const refresh = path.join(root,'refresh.json'); await writeFile(refresh,JSON.stringify({expectedRevision:1,reason:'review role approved'}));
  assert.notEqual(run('goal','policy-refresh','g1','--request',refresh,'--user-input','user-2','--adapters',adapters).status,0);
  assert.notEqual(run('goal','policy-refresh','g1','--request',refresh,'--user-input','user-1').status,0);
  const refreshed = result(run('goal','policy-refresh','g1','--request',refresh,'--user-input','user-1','--adapters',adapters));
  assert.equal(refreshed.goal.revision,2); assert.equal(refreshed.goal.policy.roles.review.model,'review-model');
  assert.deepEqual(refreshed.goal.policyChanges[0].previous,policy);
  assert.equal(result(run('goal','policy-refresh','g1','--request',refresh,'--user-input','user-1','--adapters',adapters)).summary,'Goal g1 execution policy unchanged');
  assert.equal(run('unit','start','u2','--request',unit,'--non-interactive').status,0);
});
